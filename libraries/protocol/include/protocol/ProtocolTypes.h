#ifndef PROTOCOL_PROTOCOL_TYPES_H
#define PROTOCOL_PROTOCOL_TYPES_H

#include <stddef.h>
#include <stdint.h>

#define PROTOCOL_MAGIC 0x4D43U
#define PROTOCOL_WIRE_VERSION_MAJOR 1U
#define PROTOCOL_MAX_DECODED_FRAME 256U
#define PROTOCOL_HEADER_SIZE 9U
#define PROTOCOL_CRC_SIZE 4U
#define PROTOCOL_MAX_PAYLOAD (PROTOCOL_MAX_DECODED_FRAME - PROTOCOL_HEADER_SIZE - PROTOCOL_CRC_SIZE)
#define PROTOCOL_MAX_ENCODED_FRAME 259U
#define PROTOCOL_FLAG_RESPONSE_ERROR 0x01U
#define PROTOCOL_ALLOWED_FLAGS PROTOCOL_FLAG_RESPONSE_ERROR

typedef enum {
    PROTOCOL_STATUS_OK = 0,
    PROTOCOL_STATUS_INVALID_ARGUMENT,
    PROTOCOL_STATUS_OUTPUT_TOO_SMALL,
    PROTOCOL_STATUS_FRAME_TOO_LARGE,
    PROTOCOL_STATUS_MALFORMED_COBS,
    PROTOCOL_STATUS_BAD_MAGIC,
    PROTOCOL_STATUS_UNSUPPORTED_VERSION,
    PROTOCOL_STATUS_INVALID_KIND,
    PROTOCOL_STATUS_INVALID_FLAGS,
    PROTOCOL_STATUS_LENGTH_MISMATCH,
    PROTOCOL_STATUS_BAD_CRC
} Protocol_Status;

typedef enum {
    PROTOCOL_FRAME_REQUEST = 1,
    PROTOCOL_FRAME_RESPONSE = 2,
    PROTOCOL_FRAME_EVENT = 3
} Protocol_FrameKind;

typedef struct {
    Protocol_FrameKind kind;
    uint8_t flags;
    uint16_t sequence;
    uint16_t payload_length;
    uint8_t payload[PROTOCOL_MAX_PAYLOAD];
} Protocol_Frame;

#endif
