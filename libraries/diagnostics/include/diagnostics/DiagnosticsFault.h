#ifndef DIAGNOSTICS_DIAGNOSTICS_FAULT_H
#define DIAGNOSTICS_DIAGNOSTICS_FAULT_H

#include <stdint.h>

typedef enum {
    DIAGNOSTICS_SOURCE_HOST = 1,
    DIAGNOSTICS_SOURCE_NODE = 2,
    DIAGNOSTICS_SOURCE_TOOL = 3
} Diagnostics_Source;

typedef enum {
    DIAGNOSTICS_SEVERITY_INFO = 1,
    DIAGNOSTICS_SEVERITY_WARNING = 2,
    DIAGNOSTICS_SEVERITY_ERROR = 3,
    DIAGNOSTICS_SEVERITY_FATAL = 4
} Diagnostics_Severity;

typedef enum {
    DIAGNOSTICS_DOMAIN_PROTOCOL = 1,
    DIAGNOSTICS_DOMAIN_TRANSPORT = 2,
    DIAGNOSTICS_DOMAIN_SERVICE = 3,
    DIAGNOSTICS_DOMAIN_SIMULATION = 4,
    DIAGNOSTICS_DOMAIN_RUNTIME = 5
} Diagnostics_Domain;

typedef enum {
    DIAGNOSTICS_INJECTION_EARLY_READY = 1,
    DIAGNOSTICS_INJECTION_SHORT_IRQ = 2,
    DIAGNOSTICS_INJECTION_DELAY_RESPONSE = 3,
    DIAGNOSTICS_INJECTION_DROP_ACCEPTANCE = 4,
    DIAGNOSTICS_INJECTION_CORRUPT_UART = 5,
    DIAGNOSTICS_INJECTION_TRUNCATE_UART = 6,
    DIAGNOSTICS_INJECTION_EARLY_VIRTUAL_OUTPUT = 7,
    DIAGNOSTICS_INJECTION_TASK_STALL = 8,
    DIAGNOSTICS_INJECTION_MAX = DIAGNOSTICS_INJECTION_TASK_STALL
} Diagnostics_InjectionId;

typedef struct {
    uint32_t timestamp_ms;
    uint32_t correlation_id;
    uint32_t detail;
    uint16_t code;
    uint8_t source;
    uint8_t severity;
    uint8_t domain;
} Diagnostics_Fault;

#endif
